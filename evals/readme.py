"""Generate the results block of README.md from reports/. Never edit that block by hand.

python3 -m evals.readme            # rewrite the block in README.md
python3 -m evals.readme --check    # fail if README.md is stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- results:start -->", "<!-- results:end -->"
MAIN = ("manual_ops", "manual_iso", "auto_naive", "platform")
LABEL = {
    "manual_ops": "Status quo: manual alignment, raw-frame centroid",
    "manual_iso": "Manual alignment on ISO 11146 diagnostics",
    "auto_naive": "Scripted automation, raw-frame centroid",
    "platform": "**The platform**",
}


def _load(name: str) -> dict | None:
    p = ROOT / "reports" / name
    return json.loads(p.read_text()) if p.exists() else None


def _ms(stat: dict, fmt: str, pct: bool = False) -> str:
    if stat["mean"] is None:
        return "n/a"
    k = 100.0 if pct else 1.0
    if stat["n"] > 1 and stat["sd"]:
        return f"{fmt.format(stat['mean'] * k)} ± {fmt.format(stat['sd'] * k)}"
    return fmt.format(stat["mean"] * k)


def design_table(rep: dict, names: tuple[str, ...]) -> list[str]:
    rows = [
        "| Design | Good shots / day | In spec | Far-field error p95 | Near-field error p95 | Energy reading error p95 | Damaging shots | Shots held while safe | Alignment min / day |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for n in names:
        if n not in rep["designs"]:
            continue
        s = rep["designs"][n]["summary"]
        rows.append(
            f"| {LABEL.get(n, n)} | {_ms(s['good_shots_per_day'], '{:.0f}')} | {_ms(s['in_spec_share'], '{:.1f}', True)} % | "
            f"{_ms(s['ff_error_p95_urad'], '{:.1f}')} µrad | {_ms(s['nf_error_p95_mm'], '{:.2f}')} mm | "
            f"{_ms(s['energy_report_error_p95'], '{:.2f}', True)} % | {_ms(s['damage_events'], '{:.0f}')} | "
            f"{_ms(s['false_fluence_blocks'], '{:.0f}')} | {_ms(s['align_minutes_per_day'], '{:.0f}')} |"
        )
    return rows


def ablation_table(rep: dict) -> list[str]:
    base = rep["designs"]["platform"]["summary"]
    rows = [
        "| The platform without | What it does | Good shots / day | In spec | Damaging shots | Main reason a shot was held |",
        "|---|---|---:|---:|---:|---|",
    ]
    for n, d in rep["designs"].items():
        if n in MAIN:
            continue
        s = d["summary"]
        reasons = {}
        for run in d["runs"]:
            for r in run["block_reasons"]:
                reasons[r["reason"]] = reasons.get(r["reason"], 0) + r["count"]
        top = max(reasons, key=reasons.get) if reasons else "—"
        top = top if len(top) < 70 else top[:67] + "..."
        delta = s["good_shots_per_day"]["mean"] - base["good_shots_per_day"]["mean"]
        rows.append(
            f"| {n.replace('_', ' ')} | {d['description']} | {s['good_shots_per_day']['mean']:.0f} ({delta:+.0f}) | "
            f"{100 * s['in_spec_share']['mean']:.1f} % | {s['damage_events']['mean']:.0f} | {top} |"
        )
    return rows


def gate_table(dev: dict, held: dict | None) -> list[str]:
    rows = ["| Gate | Rule | Dev (worst seed) | Held-out |", "|---|---|---:|---:|"]
    hg = {g["gate"]: g for g in held["gates"]} if held else {}
    for g in dev["gates"]:
        rule = f"≤ {g['rule']['max']}" if "max" in g["rule"] else f"≥ {g['rule']['min']}"
        h = hg.get(g["gate"])
        hv = f"{h['value']:.3f} {'pass' if h['pass'] else '**FAIL**'}" if h else "not run"
        rows.append(f"| {g['gate'].replace('_', ' ')} | {rule} | {g['value']:.3f} {'pass' if g['pass'] else '**FAIL**'} | {hv} |")
    return rows


def render_block() -> str:
    dev = _load("dev.json")
    held = _load("heldout.json")
    bench = _load("bench.json")
    elog = _load("elog.json")
    if dev is None:
        return f"{START}\n_No results yet: run `python3 -m evals.run`._\n{END}"
    days, seeds = dev["days"], len(dev["seeds"])
    out = [START, ""]
    out.append(
        f"Dev campaign: {days} simulated shifts of 8 hours on each of {seeds} beamlines (seeds {', '.join(map(str, dev['seeds']))}), "
        "every design on the same luck. Mean ± standard deviation across beamlines. Generated by `python3 -m evals.run` "
        "from `reports/dev.json`."
    )
    out.append("")
    out += design_table(dev, MAIN)
    out.append("")
    out.append(
        "A good shot is inside the experiment's spec: pointing within 5 µrad, centred within 0.75 mm on the amplifier "
        "aperture, energy within 3 % of target, on an undamaged optic. A damaging shot exceeds the optic's damage "
        "fluence (3 J/cm²); without a fluence check, every later shot through the damage site damages it further."
    )
    out.append("")
    out.append("**Ablations** (dev, mean over beamlines): the platform with one capability switched off.")
    out.append("")
    out += ablation_table(dev)
    out.append("")
    out.append("**Release gates** (config/gates.toml), applied to the platform:")
    out.append("")
    out += gate_table(dev, held)
    if held:
        out.append("")
        out.append(
            f"**Held-out campaign** ({held['days']} shifts, run once at commit `{held['commit'][:7]}` behind `reports/heldout.lock`; "
            "different mounts, more backlash, an actuator that wears on day 6, a camera that resets its gain on day 9, a reference "
            "meter whose certificate expires on day 11, hot spots on days 2 and 10):"
        )
        out.append("")
        out += design_table(held, MAIN)
    if bench:
        out.append("")
        out.append("**Beam analysis engines** (`scripts/bench.py`; identical results, checked by a property test on random frames):")
        out.append("")
        out.append("| Frame | NumPy reference | C++ beamcore | Speed-up |")
        out.append("|---|---:|---:|---:|")
        for r in bench["frames"]:
            out.append(f"| {r['pixels']} | {r['numpy_ms']:.2f} ms | {r['cpp_ms']:.2f} ms | {r['speedup']:.1f}× |")
    if elog:
        out.append("")
        out.append(
            f"**Logbook handover check** (`python3 -m evals.elog_eval`): {elog['clean_passed']} of {elog['clean_drafts']} correct drafts "
            f"posted; {elog['planted_caught']} of {elog['planted']} drafts with a planted wrong number or shot id stopped "
            "(" + ", ".join(f"{k.replace('_', ' ')} {v['caught']}/{v['n']}" for k, v in elog["by_kind"].items()) + ")."
        )
    out.append("")
    out.append(END)
    return "\n".join(out)


def main(argv: list[str]) -> int:
    path = ROOT / "README.md"
    text = path.read_text()
    block = render_block()
    start, end = text.index(START), text.index(END) + len(END)
    new = text[:start] + block + text[end:]
    if "--check" in argv:
        if new != text:
            print("README.md results are stale: run python3 -m evals.readme")
            return 1
        return 0
    path.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
